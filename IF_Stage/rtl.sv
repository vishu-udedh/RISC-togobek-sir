module if_stage (
    input  logic        clk,
    input  logic        reset,
    input  logic        stall,
    input  logic        and_out,
    input  logic [31:0] pc_signed_offset,
    output logic [31:0] address,
    output logic [31:0] pc_new
);

    logic [31:0] next_pc;

    always_comb begin
        pc_new = address + 32'd4;

        if (and_out)
            next_pc = pc_signed_offset;
        else
            next_pc = pc_new;
    end

    always_ff @(posedge clk or posedge reset) begin
        if (reset)
            address <= 32'h8000_0000;
        else if (!stall)
            address <= next_pc;
    end

endmodule